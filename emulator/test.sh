#!/usr/bin/env bash
# MiniStack(AWS 에뮬레이터) 위에서 Jangingmall 의 AWS 접점을 검증한다.
#   T0     infra Terraform 모듈(ECR, GitHub OIDC 역할, S3 images/returns 와 그 의존성) apply
#   T1-T8  ECR 배포 파이프라인 (backend CD, infra 초안, GenAI publish, AI 이미지 미러)
#   T9     backend 런타임 S3 (실제 S3ImageStorage 코드)
#
#   ./emulator/test.sh        에뮬레이터 새로 기동 -> 전체 실행
#   ./emulator/test.sh down   에뮬레이터 제거
# 필요: docker, aws cli v2, terraform, skopeo, jq, python3(+pyyaml). 레포는 ../backend ../GenAI ../infra.
set -uo pipefail
cd "$(dirname "$0")/.."

IMAGE=ministackorg/ministack:1.5.24
REGION=ap-northeast-2
OUT=emulator/out
# 계정 ID는 여기에 적지 않고, backend cd.yml 에 하드코딩된 역할 ARN 에서 읽어 온다.
ACCOUNT=$(grep -oE 'arn:aws:iam::[0-9]{12}' backend/.github/workflows/cd.yml | grep -oE '[0-9]{12}' | head -1)
ROLE="arn:aws:iam::${ACCOUNT}:role"

# 실제 AWS 로 새지 않게: 가짜 자격증명 + 로컬 엔드포인트 + 사용자 프로필/설정 파일 차단.
unset AWS_PROFILE AWS_SESSION_TOKEN
export AWS_ENDPOINT_URL=http://localhost:4566 AWS_ACCESS_KEY_ID=test AWS_SECRET_ACCESS_KEY=test \
  AWS_REGION=$REGION AWS_DEFAULT_REGION=$REGION AWS_PAGER="" \
  AWS_CONFIG_FILE=/dev/null AWS_SHARED_CREDENTIALS_FILE=/dev/null EMU_REGISTRY=localhost:4566

wait_healthy() {
  for _ in $(seq 60); do curl -fsS "$AWS_ENDPOINT_URL/_ministack/health" >/dev/null 2>&1 && return; sleep 1; done
  echo "MiniStack did not become healthy" >&2; exit 1
}

docker rm -f ministack >/dev/null 2>&1
[[ ${1:-} == down ]] && exit 0
docker run -d --name ministack -p 127.0.0.1:4566:4566 \
  -e MINISTACK_ACCOUNT_ID="$ACCOUNT" -e MINISTACK_REGION="$REGION" "$IMAGE" >/dev/null || exit 1
wait_healthy

# MiniStack 1.5.24 는 없는 imageId 를 DescribeImages 하면 빈 목록을 돌려준다. 실제 ECR 은
# ImageNotFoundException 이고, 세 레포의 "태그 존재 확인" 스텝이 전부 그 문자열에 의존한다.
# 업스트림에 고쳐지면 assert 가 깨지므로 그때 이 블록을 지운다.
docker exec -i ministack python3 - <<'PY' || exit 1
p = "/opt/ministack/ministack/services/ecr.py"
s = open(p).read()
old = "            if match:\n                filtered.append(match)\n        images = filtered"
new = ("            if match:\n                filtered.append(match)\n            else:\n"
       "                return error_response_json('ImageNotFoundException',\n"
       "                    f\"The image with imageId {iid} does not exist within the repository with name '{name}'\", 400)\n"
       "        images = filtered")
assert old in s, "MiniStack ecr.py changed; re-check whether this patch is still needed"
open(p, "w").write(s.replace(old, new))
PY
docker restart ministack >/dev/null && wait_healthy

# ---------- Terraform 밖에서 미리 있어야 하는 것 ----------
bash infra/scripts/bootstrap-github-oidc.sh && bash infra/scripts/bootstrap-github-oidc.sh   # 2회차는 건너뛰어야 함
ZONE=$(aws route53 create-hosted-zone --name midam.store --caller-reference "emu-$$" --query HostedZone.Id --output text)

# skopeo 는 스크립트가 넘기는 진짜 ECR 호스트로 접속하므로, 호스트만 에뮬레이터로 바꿔 준다.
SHIMS=$(mktemp -d)
cat >"$SHIMS/skopeo" <<EOF
#!/usr/bin/env bash
args=(); for a in "\$@"; do args+=("\$(sed -E 's#[0-9]{12}\.dkr\.ecr\.[a-z0-9-]+\.amazonaws\.com#$EMU_REGISTRY#' <<<"\$a")"); done
case "\$1" in login) tls=--tls-verify=false ;; copy) tls=--dest-tls-verify=false ;; *) exec "$(command -v skopeo)" "\$@" ;; esac
exec "$(command -v skopeo)" "\${args[0]}" "\$tls" "\${args[@]:1}"
EOF
chmod +x "$SHIMS/skopeo"

# ---------- 도우미 ----------
rm -rf "$OUT"; mkdir -p "$OUT"
pass=0 fail=0
run() { # run <id> <run_workflow.py args...>
  local id=$1; shift
  printf '\n━━ %s\n' "$id"
  python3 emulator/run_workflow.py "$@" --out "$OUT/$id.json" >"$OUT/$id.log" 2>&1
  sed -n '/^== steps/,$p' "$OUT/$id.log"
}
check() { # check <설명> <test 인자...>
  local name=$1; shift
  if "$@"; then echo "  ✅ $name"; pass=$((pass + 1)); else echo "  ❌ $name"; fail=$((fail + 1)); fi
}
out() { jq -r "$2" "$OUT/$1.json"; }
failed_with() { [ "$(out "$1" .status)" = failure ] && grep -q "$2" "$OUT/$1.log"; } # 의도한 이유로 실패했는지
ecr_digest() { aws ecr describe-images --repository-name "$1" --image-ids imageTag="$2" --query 'imageDetails[0].imageDigest' --output text 2>/dev/null; }

BE_SHA=$(git -C backend rev-parse HEAD) AI_SHA=$(git -C GenAI rev-parse HEAD) INFRA_SHA=$(git -C infra rev-parse HEAD)

# ---------- T0 infra Terraform -> MiniStack ----------
# infra 클론은 건드리지 않는다. 작업 복사본에 override 를 얹어 백엔드를 local 로, 프로바이더를 MiniStack 으로 돌린다.
printf '\n━━ T0-terraform\n'
TF=emulator/.work/terraform/environments/prod
mkdir -p emulator/.work
rsync -a --delete --exclude .terraform --exclude 'terraform.tfstate*' infra/terraform/ emulator/.work/terraform/
rm -f "$TF"/terraform.tfstate*   # 에뮬레이터가 매번 새로 뜨므로 state 도 새로
{
  printf '# Generated by emulator/test.sh\nterraform {\n  backend "local" {}\n}\n'
  for alias in '' 'alias = "us_east_1"'; do
    printf 'provider "aws" {\n  %s\n  access_key = "test"\n  secret_key = "test"\n' "$alias"
    printf '  s3_use_path_style = true\n  skip_credentials_validation = true\n  skip_metadata_api_check = true\n  endpoints {\n'
    for svc in acm cloudfront ecr iam kms route53 s3 sts wafv2; do printf '    %s = "%s"\n' "$svc" "$AWS_ENDPOINT_URL"; done
    printf '  }\n}\n'
  done
} >"$TF/zz_emulator_override.tf"
tf() { terraform -chdir="$TF" "$@" -input=false -no-color -var-file=terraform.tfvars.example -var "route53_zone_id=${ZONE##*/}"; }
POLICIES=(-target=aws_iam_policy.gha_backend_ecr -target=aws_iam_policy.gha_genai_ecr -target=aws_iam_policy.gha_genai_models_s3)
TARGETS=(-target=module.ecr -target=module.github_oidc -target=module.github_oidc_backend -target=module.github_oidc_genai
  -target=module.s3_returns -target=aws_s3_bucket_policy.returns -target=module.s3_images -target=aws_s3_bucket_policy.images)
TFLOG=$OUT/T0-terraform.log

terraform -chdir="$TF" init -input=false -no-color >"$TFLOG" 2>&1
# 이 확인이 실패하면 실제 state 버킷을 볼 수 있으므로 plan/apply 로 넘어가지 않는다.
grep -q '"type": "local"' "$TF/.terraform/terraform.tfstate" || { echo "backend is not local, aborting" >&2; exit 1; }
check "init: 백엔드가 local (실제 state 버킷 미접근)" true
tf plan "${TARGETS[@]}" >>"$TFLOG" 2>&1
check "빈 state 에서는 역할 모듈을 한 번에 plan 못 함 (for_each 가 apply 전 미정인 정책 ARN 에 의존)" \
  grep -q 'Invalid for_each argument' "$TFLOG"
tf apply -auto-approve "${POLICIES[@]}" >>"$TFLOG" 2>&1
check "1단계 apply: IAM 정책 3개" [ $? -eq 0 ]
tf apply -auto-approve "${TARGETS[@]}" >>"$TFLOG" 2>&1
check "2단계 apply: ECR, OIDC 역할, S3 images/returns + KMS, CloudFront, ACM, WAF" [ $? -eq 0 ]
tf plan -detailed-exitcode "${POLICIES[@]}" "${TARGETS[@]}" >>"$TFLOG" 2>&1
check "재plan: 변경 없음" [ $? -eq 0 ]
grep -E '^Apply complete' "$TFLOG"
check "ECR jangin-app: IMMUTABLE + scan on push" [ "$(aws ecr describe-repositories --repository-names jangin-app \
  --query 'repositories[0].[imageTagMutability,imageScanningConfiguration.scanOnPush]' --output text | tr '\t' ' ')" = "IMMUTABLE True" ]
check "backend CI 역할 신뢰 정책: repo sub 조건" bash -c "aws iam get-role --role-name jangin-gha-backend-ci \
  --query Role.AssumeRolePolicyDocument --output json | grep -q 'repo:Jangingmall/backend:ref:refs/heads/\*'"
bucket() { aws s3api list-buckets --query "Buckets[?ends_with(Name, '$1')].Name" --output text; }
IMG_BUCKET=$(bucket -s3-images) RET_BUCKET=$(bucket -s3-returns)
check "returns 버킷 기본 암호화: aws:kms" [ "$(aws s3api get-bucket-encryption --bucket "$RET_BUCKET" \
  --query 'ServerSideEncryptionConfiguration.Rules[0].ApplyServerSideEncryptionByDefault.SSEAlgorithm' --output text)" = aws:kms ]
check "images 버킷 정책: CloudFront OAC 허용 + TLS 강제" bash -c "aws s3api get-bucket-policy --bucket '$IMG_BUCKET' \
  --query Policy --output text | jq -e '[.Statement[].Sid] | contains([\"AllowCloudFrontOACGetProducts\", \"DenyInsecureTransport\"])' >/dev/null"

# ---------- T1/T2 backend CD (실제 JAR + 실제 이미지) ----------
backend_cd() {
  run "$1" backend/.github/workflows/cd.yml build-and-push --workdir backend --repo Jangingmall/backend \
    --ref refs/heads/develop --sha "$BE_SHA" --skip '^Run tests$' \
    --in-image '^Build JAR=eclipse-temurin:25-jdk-noble'
}
backend_cd T1-backend-cd-new-sha
check "job success"                            [ "$(out T1-backend-cd-new-sha .status)" = success ]
check "ecr-check: exists=false -> 빌드·push 실행"   [ "$(out T1-backend-cd-new-sha '.steps["ecr-check"].outputs.exists')" = false ]
BE_DIGEST=$(out T1-backend-cd-new-sha .steps.resolve.outputs.digest)
check "워크플로 digest == ECR 의 sha-<sha> digest" [ -n "$BE_DIGEST" -a "$BE_DIGEST" = "$(ecr_digest jangin-app "sha-$BE_SHA")" ]

backend_cd T2-backend-cd-rerun
check "job success"                            [ "$(out T2-backend-cd-rerun .status)" = success ]
check "ecr-check: exists=true -> 빌드 건너뜀"      [ "$(out T2-backend-cd-rerun .steps.push.outcome)" = skipped ]
check "재사용 digest 가 T1 과 동일"                 [ "$(out T2-backend-cd-rerun .steps.resolve.outputs.digest)" = "$BE_DIGEST" ]

# ---------- T3 IMMUTABLE: 같은 태그에 다른 이미지 push 는 거부 ----------
printf '\n━━ T3-immutable-tag\n'
docker pull -q busybox:1.36 >/dev/null && docker tag busybox:1.36 "$EMU_REGISTRY/jangin-app:sha-$BE_SHA"
check "다른 이미지를 같은 태그로 push -> 거부" bash -c "! docker push '$EMU_REGISTRY/jangin-app:sha-$BE_SHA' >/dev/null 2>&1"
check "태그의 digest 불변"                    [ "$(ecr_digest jangin-app "sha-$BE_SHA")" = "$BE_DIGEST" ]

# ---------- T4 infra promote 초안 x backend CD 가 올린 이미지 (태그 규칙 불일치 재현) ----------
promote() { # promote <id> <추가 인자...>
  local id=$1; shift
  run "$id" infra/ci-cd/promote.yml promote --workdir infra --repo Jangingmall/backend --event workflow_dispatch \
    --sha "$INFRA_SHA" --var ECR_REPOSITORY=jangin-app --var "AWS_ROLE_ARN=$ROLE/jangin-gha-infra-prod" \
    --input "sha=${BE_SHA:0:7}" --var "STAGING_VERIFIED_SHA=$BE_SHA" "$@"
}
promote T4-promote-vs-backend-tag --var "STAGING_VERIFIED_DIGEST=$BE_DIGEST"
check "promote 는 <7자리> 태그를 찾고 backend CD 는 sha-<40자리> 로 올림 -> 승격 실패(알려진 불일치)" \
  failed_with T4-promote-vs-backend-tag ImageNotFoundException

# ---------- T5/T6 infra build-deploy -> promote 초안 (스텁 이미지) ----------
run T5-infra-build-deploy infra/ci-cd/build-deploy.yml cd --workdir backend --repo Jangingmall/backend \
  --ref refs/heads/develop --sha "$BE_SHA" --var ECR_REPOSITORY=jangin-app \
  --var "AWS_ROLE_ARN=$ROLE/jangin-gha-backend-ci" --var TEST_COMMAND=true --stub-build
check "job success"                                 [ "$(out T5-infra-build-deploy .status)" = success ]
check "batch-get-image ImageNotFound -> exists=false" [ "$(out T5-infra-build-deploy .steps.existing.outputs.exists)" = false ]
BD_DIGEST=$(out T5-infra-build-deploy .steps.image.outputs.digest)
check "digest == ECR 의 <7자리> 태그 digest"          [ -n "$BD_DIGEST" -a "$BD_DIGEST" = "$(ecr_digest jangin-app "${BE_SHA:0:7}")" ]

promote T6a-promote-verified --var "STAGING_VERIFIED_DIGEST=$BD_DIGEST"
check "job success"                    [ "$(out T6a-promote-verified .status)" = success ]
check "prod 후보 = <acct>.dkr.ecr...@digest" \
  [ "$(out T6a-promote-verified .steps.image.outputs.image_ref)" = "$ACCOUNT.dkr.ecr.$REGION.amazonaws.com/jangin-app@$BD_DIGEST" ]
promote T6b-promote-wrong-digest --var "STAGING_VERIFIED_DIGEST=sha256:$(printf '0%.0s' $(seq 64))"
check "staging 검증 digest 와 다르면 실패" failed_with T6b-promote-wrong-digest 'staging 검증 digest와 ECR digest가 다릅니다'

# ---------- T7 GenAI publish (chatbot-api leg, 스텁 이미지) ----------
genai() { # genai <id> <추가 인자...>
  local id=$1; shift
  run "$id" GenAI/.github/workflows/genai-ci.yml publish --workdir GenAI --repo Jangingmall/GenAI \
    --ref refs/heads/main --sha "$AI_SHA" --matrix service=chatbot-api --stub-build \
    --skip '^Check runner storage$' "$@"
}
genai T7a-genai-no-role-var
check "AWS_ROLE_ARN 변수 없으면 실패"    failed_with T7a-genai-no-role-var 'AWS_ROLE_ARN is not set'
check "AWS 인증 스텝에 도달하지 않음"      [ "$(out T7a-genai-no-role-var '.steps._4.outcome')" = skipped ]
genai T7b-genai-publish --var "AWS_ROLE_ARN=$ROLE/jangin-gha-genai-ci"
check "job success"               [ "$(out T7b-genai-publish .status)" = success ]
check "existing: exists=false"    [ "$(out T7b-genai-publish .steps.existing.outputs.exists)" = false ]
AI_DIGEST=$(out T7b-genai-publish .steps.image.outputs.digest)
check "digest == ECR 의 <sha> 태그 digest" [ -n "$AI_DIGEST" -a "$AI_DIGEST" = "$(ecr_digest jangin-ai/chatbot-api "$AI_SHA")" ]
genai T7c-genai-rerun --var "AWS_ROLE_ARN=$ROLE/jangin-gha-genai-ci"
check "재실행 -> 빌드 건너뜀"        [ "$(out T7c-genai-rerun .steps.image.outcome)" = skipped ]
check "Summary 에 reused-existing-immutable-tag + 같은 digest" \
  bash -c "jq -r .summary '$OUT/T7c-genai-rerun.json' | grep -q reused-existing-immutable-tag && jq -r .summary '$OUT/T7c-genai-rerun.json' | grep -q '$AI_DIGEST'"

# ---------- T8 infra AI 이미지 미러 (skopeo, 멀티 아키텍처 digest 보존) ----------
SRC_DIGEST=sha256:$(skopeo inspect --raw docker://public.ecr.aws/aws-cli/aws-cli:latest | shasum -a 256 | cut -d' ' -f1)
mirror() { # mirror <id> <source_digest>
  PATH="$SHIMS:$PATH" run "$1" infra/.github/workflows/ai-image-mirror.yml mirror --workdir infra \
    --repo Jangingmall/infra --event workflow_dispatch --sha "$INFRA_SHA" \
    --var "AWS_ROLE_ARN=$ROLE/jangin-gha-infra-prod" --input runtime=model-fetch --input "source_digest=$2" \
    --skip '^Install registry copy tool$'
}
mirror T8a-mirror-tag-rejected latest
check "digest 가 아닌 태그 입력 -> 거부" failed_with T8a-mirror-tag-rejected 'must be a pinned sha256 digest'
check "AWS 인증 스텝에 도달하지 않음"    [ "$(out T8a-mirror-tag-rejected '.steps._2.outcome')" = skipped ]
mirror T8b-mirror-copy "$SRC_DIGEST"
check "job success"                    [ "$(out T8b-mirror-copy .status)" = success ]
check "ECR digest == 원본 digest (보존)" [ "${#SRC_DIGEST}" -eq 71 -a "$(ecr_digest jangin-ai/model-fetch "sha256-${SRC_DIGEST#sha256:}")" = "$SRC_DIGEST" ]
mirror T8c-mirror-rerun "$SRC_DIGEST"
check "재실행 멱등 (기존 태그 digest 일치)"  [ "$(out T8c-mirror-rerun .status)" = success ]

# ---------- T9 backend 런타임 S3: 실제 S3ImageStorage 코드 x Terraform 이 만든 버킷 ----------
# T1 이 만든 bootJar 레이어를 클래스패스로 쓴다. HTTPS 는 죽은 프록시로 보내 실제 AWS 로 나갈 길을 막는다.
printf '\n━━ T9-backend-s3-storage\n'
docker run --rm --network container:ministack -v "$PWD/backend/build/extracted:/app:ro" -v "$PWD/emulator:/emu:ro" \
  -e AWS_ENDPOINT_URL_S3=http://127.0.0.1:4566 -e AWS_ACCESS_KEY_ID -e AWS_SECRET_ACCESS_KEY -e AWS_REGION \
  -e IMAGE_UPLOAD_BUCKET="$IMG_BUCKET" -e IMAGE_RETURN_BUCKET="$RET_BUCKET" \
  eclipse-temurin:25-jdk-noble java -Dhttps.proxyHost=127.0.0.1 -Dhttps.proxyPort=9 \
  -cp '/app/application/BOOT-INF/classes:/app/dependencies/BOOT-INF/lib/*:/app/snapshot-dependencies/BOOT-INF/lib/*' \
  /emu/S3StorageCheck.java >"$OUT/T9-backend-s3-storage.log" 2>&1
check "S3StorageCheck 실행 완료" [ $? -eq 0 ]
grep -E '✅|❌' "$OUT/T9-backend-s3-storage.log"
pass=$((pass + $(grep -c '✅' "$OUT/T9-backend-s3-storage.log"))) fail=$((fail + $(grep -c '❌' "$OUT/T9-backend-s3-storage.log")))

printf '\n━━ 결과: %d passed, %d failed  (스텝 로그: %s/*.log)\n' "$pass" "$fail" "$OUT"
[ "$fail" -eq 0 ]
